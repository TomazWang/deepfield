import { readdir, readFile, writeFile, ensureDir } from 'fs-extra';
import fsExtra from 'fs-extra';
const { readdir: fseReaddir, readFile: fseReadFile, writeFile: fseWriteFile, ensureDir: fseEnsureDir, pathExists } = fsExtra;
import { join, relative, dirname, basename, extname } from 'path';
import matter from 'gray-matter';
import type { TransformResult } from './types.js';

const TIER_DIRS = ['context', 'tech-design', 'implementation', 'cross-cutting'];
const LEGACY_DIR = 'domains';

/**
 * Derive a human-readable title from a filename.
 * e.g. "auth-service" → "Auth Service", "tech-design" → "Tech Design"
 */
function filenameToTitle(name: string): string {
  return name
    .replace(/[-_]/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

/**
 * Extract title from the first # heading in markdown content.
 * Falls back to filename-derived title.
 */
function extractTitle(content: string, fallback: string): string {
  const match = content.match(/^#\s+(.+)$/m);
  return match ? match[1].trim() : filenameToTitle(fallback);
}

/**
 * Shorten a sidebar label: strip leading "Domain Name — " prefix if present.
 */
function shortenLabel(title: string): string {
  // "Auth Service — Technical Design" → "Technical Design"
  const dashMatch = title.match(/^.+\s[—–-]\s+(.+)$/);
  return dashMatch ? dashMatch[1] : title;
}

/**
 * Detect the workspace structure type from the snapshot directory.
 */
async function detectStructure(
  snapshotPath: string
): Promise<'3-tier' | 'domains' | 'flat'> {
  const tierCount = (
    await Promise.all(TIER_DIRS.map((d) => pathExists(join(snapshotPath, d))))
  ).filter(Boolean).length;

  if (tierCount >= 2) return '3-tier';
  if (await pathExists(join(snapshotPath, LEGACY_DIR))) return 'domains';
  return 'flat';
}

/**
 * Recursively collect all .md files under a directory.
 * Returns paths relative to the base directory.
 */
async function collectMarkdownFiles(dir: string, base: string = dir): Promise<string[]> {
  const entries = await fseReaddir(dir, { withFileTypes: true });
  const results: string[] = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...(await collectMarkdownFiles(fullPath, base)));
    } else if (entry.isFile() && extname(entry.name) === '.md') {
      results.push(relative(base, fullPath));
    }
  }

  return results.sort();
}

/**
 * Process a single markdown file: inject Docusaurus frontmatter if missing,
 * write to docs output path.
 */
async function processMarkdownFile(
  srcPath: string,
  destPath: string,
  relativePath: string,
  position: number
): Promise<void> {
  const raw = await fseReadFile(srcPath, 'utf-8');
  const parsed = matter(raw);

  // Don't add frontmatter if it already exists and has a title
  if (parsed.data.title) {
    await fseEnsureDir(dirname(destPath));
    await fseWriteFile(destPath, raw, 'utf-8');
    return;
  }

  const fileBase = basename(relativePath, '.md');
  const title = extractTitle(parsed.content, fileBase);
  const sidebarLabel = shortenLabel(title);

  const frontmatter = {
    title,
    sidebar_label: sidebarLabel,
    sidebar_position: position,
  };

  const output = matter.stringify(parsed.content, frontmatter);
  await fseEnsureDir(dirname(destPath));
  await fseWriteFile(destPath, output, 'utf-8');
}


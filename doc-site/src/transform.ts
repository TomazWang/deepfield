/**
 * Mirror all markdown from snapshotPath into docsDestPath with Docusaurus
 * frontmatter injected. Returns transform metadata.
 */
export async function transformSnapshot(
  snapshotPath: string,
  docsDestPath: string
): Promise<TransformResult> {
  const structure = await detectStructure(snapshotPath);
  const allFiles = await collectMarkdownFiles(snapshotPath);

  // Track per-directory position counters
  const positionCounters: Record<string, number> = {};

  let docsCount = 0;

  for (const relPath of allFiles) {
    const srcFull = join(snapshotPath, relPath);
    const dirKey = dirname(relPath);
    positionCounters[dirKey] = (positionCounters[dirKey] ?? 0) + 1;
    const position = positionCounters[dirKey];

    // SNAPSHOT.md → intro.md (landing page)
    if (basename(relPath) === 'SNAPSHOT.md') {
      const raw = await fseReadFile(srcFull, 'utf-8');
      const parsed = matter(raw);
      const introFrontmatter = {
        title: 'Knowledge Base Overview',
        sidebar_label: 'Overview',
        sidebar_position: 1,
        slug: '/',
      };
      const output = matter.stringify(parsed.content, introFrontmatter);
      const destFull = join(docsDestPath, 'intro.md');
      await fseEnsureDir(dirname(destFull));
      await fseWriteFile(destFull, output, 'utf-8');
      docsCount++;
      continue;
    }

    const destFull = join(docsDestPath, relPath);
    await processMarkdownFile(srcFull, destFull, relPath, position);
    docsCount++;
  }

  const sidebarCategories =
    structure === '3-tier'
      ? TIER_DIRS
      : structure === 'domains'
        ? [LEGACY_DIR]
        : ['.'];

  return { docsCount, sidebarCategories, structureType: structure };
}

export { generateSidebars, detectStructure };
